    <link rel="stylesheet" href="../assets/css/admin.css">
</head>
<body>
    <div class="login-page">
        <div class="login-box">
            <h1><i class="fas fa-shield-alt"></i> Admin Panel</h1>
            <p>Sign in to manage your portfolio</p>
            
            <?php if ($error): ?>
            <div class="alert alert-danger"><?php echo $error; ?></div>
            <?php endif; ?>
            
            <form method="POST">
                <div class="form-group">
                    <label>Username</label>
                    <input type="text" name="username" required placeholder="admin" value="<?php echo htmlspecialchars($_POST['username'] ?? ''); ?>">
                </div>
                <div class="form-group">
                    <label>Password</label>
                    <input type="password" name="password" required placeholder="Enter password">
                </div>
                <button type="submit" class="btn btn-primary">
                    <i class="fas fa-sign-in-alt"></i> Login
                </button>
            </form>
            <p style="margin-top: 1.5rem; font-size: 0.8rem; color: var(--gray);">
                Default: username = <strong>admin</strong>, password = <strong>admin123</strong>
            </p>
        </div>
    </div>
